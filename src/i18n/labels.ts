/** « SOME_CODE » → « Some code » : repli lisible pour un code inconnu. */
export function humanizeCode(code: string): string {
  const text = code.replace(/_/g, " ").toLowerCase().trim();
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** Libellé lisible et traduit d'un code métier (« - » si absent). */
export function codeLabel(code: string | null | undefined, domain?: keyof typeof DOMAIN_LABELS | string): string {
  if (code == null || code === "") return "-";
  const key = String(code).trim();
  const label = (domain && DOMAIN_LABELS[domain]?.[key]) ?? LABELS[key];
  return label ? tr(label) : /^[A-Z0-9_]+$/.test(key) ? humanizeCode(key) : key;
}

/**
 * Remplace les codes métier connus présents dans un texte libre (ex. messages de
 * notification générés côté serveur : « Incident ACCIDENT (CRITICAL) … »).
 */
export function humanizeCodesInText(text: string | null | undefined): string {
  if (!text) return "";
  return text.replace(/\b[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*\b/g, (match) =>
    LABELS[match] && match.length > 2 && !["OK", "DATE", "EMAIL", "TOTAL", "SHELL"].includes(match)
      ? tr(LABELS[match]).toLowerCase()
      : match
  );
}
